"""Emit a board test vector for the AXI4-Lite engine, as sourceable Tcl.

The vector is the exact same case the simulation testbench checks, so a board
that disagrees with it disagrees with the emulator, and the emulator is what
every accuracy and error-bound result in the paper is stated against.

    python board_vectors.py --wl 56 --fl 28 --mults 8 --crot 3 --cvec 2 \
                            --host-setup --name heston_aad_z7h
    -> build/heston_aad_z7h_lite_vector.tcl

    python board_vectors.py ... --sweep 48 [--seed 2026]
    -> build/heston_aad_z7h_lite_sweep.tcl     (run with zedboard/run_sweep.tcl)

A sweep is the two fixed CASES plus N random parameter sets from the verified
domain (ranges.DOMAIN). The seed differs from the one ranges.py fitted the
shifter ranges to, so the sweep tests cases the hardware was not tuned on. A
draw is kept only if every variable shift in the term loop -- the part the
FPGA runs -- falls inside its own fitted range. The hardware checks each
shared multiplier against the union of its operations' ranges, so a kept case
must give range_err = 0 and bit-exact outputs; skipped draws are counted.

For a host-setup design the 19 hs_* constants are computed here, on the PC, in
the same fixed-point arithmetic as the datapath (hardware/gen/host.py is the
bit-exact specification). That is deliberate for first bring-up: the Zynq-7000
PS is 32-bit ARMv7 with no __int128, so a C port needs a hand-written
64x64->128 multiply, and there is no reason to debug that at the same time as
the board. Phase 2 moves setup/finish onto the ARM.
"""
import argparse
import os
import random

import heston as H
import ranges as RG
from wrappers import BUILD, CASES, LITE_CTRL, LITE_STAT, build_core, lite_map


def _ports(a):
    W = a.wl
    dp, gen, _ = build_core(a, False, a.name)
    in_ports = [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    if a.host_setup:
        in_ports += [(pt, gen.width(dp.g.nodes[nid])) for nid, pt in sorted(gen.host_inputs.items())]
        out_ports = ["sum_" + x for x in dp.acc_names]
    else:
        out_ports = list(H.OUTPUTS)
    return dp, gen, in_ports, out_ports, lite_map(in_ports, out_ports, W)


def case_io(a, dp, gen, in_ports, out_ports, regs, pv, call):
    """(writes, expected) for one parameter set: [(offset, word)], {port: int}"""
    q = H.quantize_inputs(pv, call, a.fl)
    exp, tr = H.emulate(dp, q, a.terms)
    if a.host_setup:
        exp = {"sum_" + x: tr["acc"][x] for x in dp.acc_names}
    vals = {n: q[n] for n in H.PARAMS}
    vals["is_call"] = q["is_call"]
    if a.host_setup:
        for nid, pt in sorted(gen.host_inputs.items()):
            vals[pt] = int(tr["setup"][nid])
    writes = []
    for x, w in in_ports:
        raw = vals[x] & ((1 << w) - 1)
        for k in range(regs[x]["words"]):
            writes.append((regs[x]["offset"] + 4 * k, (raw >> (32 * k)) & 0xFFFFFFFF))
    return writes, {o: exp[o] for o in out_ports}


def _header(a, extra):
    return ["# Generated by hardware/gen/board_vectors.py -- do not edit by hand.",
            "# Design: %s_lite   %s" % (a.name, extra),
            "set VEC_WL %d" % a.wl,
            "set VEC_FL %d" % a.fl,
            "set VEC_CTRL 0x%03x" % LITE_CTRL,
            "set VEC_STAT 0x%03x" % LITE_STAT]


def vector(a, case=0):
    dp, gen, in_ports, out_ports, regs = _ports(a)
    pv, call = CASES[case]
    writes, exp = case_io(a, dp, gen, in_ports, out_ports, regs, pv, call)
    t = ["# Generated by hardware/gen/board_vectors.py -- do not edit by hand.",
         "# Design: %s_lite   case: S0=%g K=%g T=%g r=%g v0=%g kappa=%g theta=%g xi=%g rho=%g %s"
         % ((a.name,) + tuple(pv) + ("call" if call else "put",)),
         "# Q%d.%d ; %d input words ; %d outputs" % (a.wl - a.fl, a.fl, len(writes), len(out_ports))]
    t += _header(a, "")[2:]
    t.append("set VEC_WRITES {")
    t += ["  {0x%03x 0x%08x}" % (o, d) for o, d in writes]
    t.append("}")
    t.append("set VEC_EXPECT {")
    for o in out_ports:
        t.append("  {%-12s 0x%03x %s}" % (o, regs[o]["offset"], _dec(exp[o])))
    t.append("}")
    path = os.path.join(BUILD, a.name + "_lite_vector.tcl")
    os.makedirs(BUILD, exist_ok=True)
    open(path, "w").write("\n".join(t) + "\n")
    print("wrote %s: %d writes, %d expected outputs" % (path, len(writes), len(out_ports)))
    return path


def shifts_in_range(dp, rmap, pv, call, parts=("term",)):
    """True if every variable shift in `parts` stays inside its fitted range."""
    g = dp.g
    var = [n for n in RG.variable_nodes(g) if n.part in parts]
    q = H.quantize_inputs(pv, call, g.fl)
    vals = g.eval_fixed(q, part="setup")
    for k in range(H.N_TERMS):
        tv = list(vals)
        tv[dp.k] = k
        g.eval_fixed(dict(q, k=k), values=tv, part="term")
        for n in var:
            sh = RG.fixed_shift(g, n) - tv[n.args[-1] if n.op == "mul" else n.args[1]]
            lo, hi = rmap[n.id]
            if not lo <= sh <= hi:
                return False
    return True


def sweep_cases(dp, n, seed):
    """the fixed CASES, then n in-range random draws; returns (cases, skipped)"""
    rmap = RG.get(dp, BUILD)
    rng = random.Random(seed)
    cases, skipped = list(CASES), 0
    while len(cases) < len(CASES) + n:
        pv = [rng.uniform(*RG.DOMAIN[p]) for p in H.PARAMS]
        call = rng.random() < 0.5
        if shifts_in_range(dp, rmap, pv, call):
            cases.append((pv, call))
        else:
            skipped += 1
    return cases, skipped


def sweep(a, n, seed):
    dp, gen, in_ports, out_ports, regs = _ports(a)
    cases, skipped = sweep_cases(dp, n, seed)
    t = _header(a, "sweep: %d cases (2 fixed + %d random, seed %d; %d out-of-range draws skipped)"
                % (len(cases), n, seed, skipped))
    t.append("set VEC_CASES {")
    for i, (pv, call) in enumerate(cases):
        writes, exp = case_io(a, dp, gen, in_ports, out_ports, regs, pv, call)
        label = "S0=%.6g K=%.6g T=%.6g r=%.6g v0=%.6g kappa=%.6g theta=%.6g xi=%.6g rho=%.6g %s" % (
            tuple(pv) + ("call" if call else "put",))
        t.append("  {{%s}" % label)
        t.append("   {" + " ".join("{0x%03x 0x%08x}" % wd for wd in writes) + "}")
        t.append("   {" + " ".join("{%s 0x%03x %s}" % (o, regs[o]["offset"], _dec(exp[o])) for o in out_ports) + "}}")
    t.append("}")
    path = os.path.join(BUILD, a.name + "_lite_sweep.tcl")
    os.makedirs(BUILD, exist_ok=True)
    open(path, "w").write("\n".join(t) + "\n")
    print("wrote %s: %d cases, %d out-of-range draws skipped" % (path, len(cases), skipped))
    return path


def _dec(v):
    """signed decimal: Tcl has arbitrary-precision integers, so no splitting"""
    return str(v)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--wl", type=int, default=56)
    ap.add_argument("--fl", type=int, default=28)
    ap.add_argument("--mults", type=int, default=8)
    ap.add_argument("--crot", type=int, default=3)
    ap.add_argument("--cvec", type=int, default=2)
    ap.add_argument("--pipe-cordic", action="store_true")
    ap.add_argument("--host-setup", action="store_true")
    ap.add_argument("--terms", type=int, default=128)
    ap.add_argument("--name", default="heston_aad_z7h")
    ap.add_argument("--case", type=int, default=0)
    ap.add_argument("--sweep", type=int, default=0, help="emit N random cases instead of one")
    ap.add_argument("--seed", type=int, default=2026, help="sweep seed (ranges.py fitted on 11)")
    a = ap.parse_args()
    if a.sweep:
        sweep(a, a.sweep, a.seed)
    else:
        vector(a, a.case)
