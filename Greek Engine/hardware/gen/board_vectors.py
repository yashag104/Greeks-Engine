"""Emit a board test vector for the AXI4-Lite engine, as sourceable Tcl.

The vector is the exact same case the simulation testbench checks, so a board
that disagrees with it disagrees with the emulator, and the emulator is what
every accuracy and error-bound result in the paper is stated against.

    python board_vectors.py --wl 56 --fl 28 --mults 8 --crot 3 --cvec 2 \
                            --host-setup --name heston_aad_z7h
    -> build/heston_aad_z7h_lite_vector.tcl

For a host-setup design the 19 hs_* constants are computed here, on the PC, in
the same fixed-point arithmetic as the datapath (hardware/gen/host.py is the
bit-exact specification). That is deliberate for first bring-up: the Zynq-7000
PS is 32-bit ARMv7 with no __int128, so a C port needs a hand-written
64x64->128 multiply, and there is no reason to debug that at the same time as
the board. Phase 2 moves setup/finish onto the ARM.
"""
import argparse
import os

import heston as H
from wrappers import BUILD, CASES, LITE_CTRL, LITE_STAT, build_core, lite_map


def vector(a, case=0):
    W, fl = a.wl, a.fl
    dp, gen, _ = build_core(a, False, a.name)
    host = a.host_setup
    in_ports = [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    if host:
        in_ports += [(pt, gen.width(dp.g.nodes[nid])) for nid, pt in sorted(gen.host_inputs.items())]
        out_ports = ["sum_" + x for x in dp.acc_names]
    else:
        out_ports = list(H.OUTPUTS)
    regs = lite_map(in_ports, out_ports, W)

    pv, call = CASES[case]
    q = H.quantize_inputs(pv, call, fl)
    exp, tr = H.emulate(dp, q, a.terms)
    if host:
        exp = {"sum_" + x: tr["acc"][x] for x in dp.acc_names}
    vals = {n: q[n] for n in H.PARAMS}
    vals["is_call"] = q["is_call"]
    if host:
        for nid, pt in sorted(gen.host_inputs.items()):
            vals[pt] = int(tr["setup"][nid])

    writes = []
    for x, w in in_ports:
        raw = vals[x] & ((1 << w) - 1)
        for k in range(regs[x]["words"]):
            writes.append((regs[x]["offset"] + 4 * k, (raw >> (32 * k)) & 0xFFFFFFFF))

    t = ["# Generated by hardware/gen/board_vectors.py -- do not edit by hand.",
         "# Design: %s_lite   case: S0=%g K=%g T=%g r=%g v0=%g kappa=%g theta=%g xi=%g rho=%g %s"
         % ((a.name,) + tuple(pv) + ("call" if call else "put",)),
         "# Q%d.%d ; %d input words ; %d outputs" % (W - fl, fl, len(writes), len(out_ports)),
         "set VEC_WL %d" % W,
         "set VEC_FL %d" % fl,
         "set VEC_CTRL 0x%03x" % LITE_CTRL,
         "set VEC_STAT 0x%03x" % LITE_STAT,
         "set VEC_WRITES {"]
    t += ["  {0x%03x 0x%08x}" % (o, d) for o, d in writes]
    t.append("}")
    t.append("set VEC_EXPECT {")
    for o in out_ports:
        t.append("  {%-12s 0x%03x %s}" % (o, regs[o]["offset"], _dec(exp[o])))
    t.append("}")
    path = os.path.join(BUILD, a.name + "_lite_vector.tcl")
    os.makedirs(BUILD, exist_ok=True)
    open(path, "w").write("\n".join(t) + "\n")
    print("wrote %s: %d writes, %d expected outputs" % (path, len(writes), len(out_ports)))
    return path


def _dec(v):
    """signed decimal: Tcl has arbitrary-precision integers, so no splitting"""
    return str(v)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--wl", type=int, default=56)
    ap.add_argument("--fl", type=int, default=28)
    ap.add_argument("--mults", type=int, default=8)
    ap.add_argument("--crot", type=int, default=3)
    ap.add_argument("--cvec", type=int, default=2)
    ap.add_argument("--pipe-cordic", action="store_true")
    ap.add_argument("--host-setup", action="store_true")
    ap.add_argument("--terms", type=int, default=128)
    ap.add_argument("--name", default="heston_aad_z7h")
    ap.add_argument("--case", type=int, default=0)
    a = ap.parse_args()
    vector(a, a.case)
