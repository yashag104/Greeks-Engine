# ---------------------------------------------------------------- bump
def bump_wrapper(name, pricer, wl, fl):
    W = wl
    p = []
    P = p.append
    P("`timescale 1ns / 1ps")
    P("// Generated by hardware/gen/wrappers.py: bump-and-reprice baseline on %s." % pricer)
    P("module %s (" % name)
    P("    input wire clk, input wire rst, input wire start,")
    for n in H.PARAMS:
        P("    input wire signed [%d:0] %s, input wire signed [%d:0] h_%s, input wire signed [%d:0] inv2h_%s," % (W - 1, n, W - 1, n, W - 1, n))
    P("    input wire is_call,")
    for o in H.OUTPUTS:
        P("    output reg signed [%d:0] %s," % (W - 1, o))
    P("    output reg done, output reg range_err);")
    P("    localparam NP = 9, NPASS = 19, FL = %d;" % fl)
    P("    reg signed [%d:0] base [0:NP-1]; reg signed [%d:0] hv [0:NP-1]; reg signed [%d:0] iv [0:NP-1];" % (W - 1, W - 1, W - 1))
    P("    reg signed [%d:0] cur [0:NP-1]; reg signed [%d:0] pv [0:NPASS-1];" % (W - 1, W - 1))
    P("    reg call_r, pstart; wire pdone, perr; wire signed [%d:0] pprice;" % (W - 1))
    P("    %s pricer (.clk(clk), .rst(rst), .start(pstart), %s, .is_call(call_r), .price(pprice), .done(pdone), .range_err(perr));"
      % (pricer, ", ".join(".%s(cur[%d])" % (n, i) for i, n in enumerate(H.PARAMS))))
    P("    reg [2:0] st; reg [4:0] pass; reg [3:0] gi; integer i;")
    P("    reg signed [%d:0] prod;" % (2 * W - 1))
    P("    localparam IDLE = 0, SETUP = 1, RUN = 2, WAIT = 3, DIFF = 4, OUT = 5;")
    P("    always @(posedge clk) begin")
    P("        if (rst) begin st <= IDLE; done <= 0; pstart <= 0; end")
    P("        else begin")
    P("            done <= 0; pstart <= 0;")
    P("            case (st)")
    P("            IDLE: if (start) begin")
    for i, n in enumerate(H.PARAMS):
        P("                base[%d] <= %s; hv[%d] <= h_%s; iv[%d] <= inv2h_%s;" % (i, n, i, n, i, n))
    P("                call_r <= is_call; pass <= 0; st <= SETUP; range_err <= 0;")
    P("            end")
    P("            SETUP: begin")
    P("                for (i = 0; i < NP; i = i + 1)")
    P("                    if (pass != 0 && i == (pass - 1) / 2) cur[i] <= ((pass - 1) % 2 == 0) ? base[i] + hv[i] : base[i] - hv[i];")
    P("                    else cur[i] <= base[i];")
    P("                st <= RUN;")
    P("            end")
    P("            RUN: begin pstart <= 1; st <= WAIT; end")
    P("            WAIT: if (pdone) begin")
    P("                pv[pass] <= pprice; if (perr) range_err <= 1;")
    P("                if (pass == NPASS - 1) begin gi <= 0; st <= DIFF; end")
    P("                else begin pass <= pass + 1; st <= SETUP; end")
    P("            end")
    P("            DIFF: begin")
    P("                prod = (pv[2*gi+1] - pv[2*gi+2]) * iv[gi];")
    P("                prod = (prod + ($signed({{%d{1'b0}}, 1'b1}) <<< (FL - 1))) >>> FL;" % (2 * W - 1))
    P("                case (gi)")
    for i, (o, _) in enumerate(SENS):
        P("                %d: %s <= prod[%d:0];" % (i, o, W - 1))
    P("                endcase")
    P("                if (gi == NP - 1) st <= OUT; else gi <= gi + 1;")
    P("            end")
    P("            OUT: begin price <= pv[0]; done <= 1; st <= IDLE; end")
    P("            endcase")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(p) + "\n"


def bump_emulate(dp_price, q, hq, iq, n_terms=H.N_TERMS):
    prices = []
    for pas in range(19):
        qq = dict(q)
        if pas:
            i = (pas - 1) // 2
            name = H.PARAMS[i]
            qq[name] = q[name] + (hq[name] if (pas - 1) % 2 == 0 else -hq[name])
        out, _ = H.emulate(dp_price, qq, n_terms)
        prices.append(out["price"])
    res = {"price": prices[0]}
    for i, (o, name) in enumerate(SENS):
        res[o] = rshift_round((prices[2 * i + 1] - prices[2 * i + 2]) * iq[name], dp_price.g.fl)
    return res


# ---------------------------------------------------------------- AXI
def axi_wrapper(name, core, wl, in_ports=None, out_ports=None):
    """in_ports: [(port, width)] packed lane by lane (WL bits each, LSB lane first);
    out_ports: [port] (WL bits each). Defaults: full on-chip AAD engine."""
    W = wl
    in_ports = in_ports or [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    out_ports = out_ports or list(H.OUTPUTS)
    NI, NO = len(in_ports), len(out_ports)
    p = []
    P = p.append
    P("`timescale 1ns / 1ps")
    P("// Generated by hardware/gen/wrappers.py: AXI4-Stream wrapper for %s." % core)
    P("// in : %d lanes of %d bits: %s" % (NI, W, ", ".join(x for x, _ in in_ports)))
    P("// out: %d lanes of %d bits: %s ; m_axis_tuser = range_err" % (NO, W, ", ".join(out_ports)))
    P("module %s (" % name)
    P("    input wire aclk, input wire aresetn,")
    P("    input wire [%d:0] s_axis_tdata, input wire s_axis_tvalid, output wire s_axis_tready, input wire s_axis_tlast," % (NI * W - 1))
    P("    output wire [%d:0] m_axis_tdata, output wire m_axis_tvalid, input wire m_axis_tready, output wire m_axis_tlast," % (NO * W - 1))
    P("    output wire m_axis_tuser);   // 1 = range_err: an input outside the verified domain, results invalid")
    for x, w in in_ports:
        P("    reg %sr_%s;" % (("signed [%d:0] " % (w - 1)) if w > 1 else "", x))
    P("    reg go, uerr; wire done, rerr;")
    P("    wire signed [%d:0] %s;" % (W - 1, ", ".join("o_" + o for o in out_ports)))
    P("    %s core (.clk(aclk), .rst(!aresetn), .start(go), %s, %s, .done(done), .range_err(rerr));"
      % (core, ", ".join(".%s(r_%s)" % (x, x) for x, _ in in_ports), ", ".join(".%s(o_%s)" % (o, o) for o in out_ports)))
    P("    localparam IDLE = 0, BUSY = 1, OUT = 2;")
    P("    reg [1:0] st;")
    P("    reg [%d:0] obuf;" % (NO * W - 1))
    P("    assign s_axis_tready = (st == IDLE);")
    P("    assign m_axis_tvalid = (st == OUT);")
    P("    assign m_axis_tlast = 1'b1;")
    P("    assign m_axis_tdata = obuf;")
    P("    assign m_axis_tuser = uerr;")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin st <= IDLE; go <= 0; end")
    P("        else begin")
    P("            go <= 0;")
    P("            case (st)")
    P("            IDLE: if (s_axis_tvalid) begin")
    for i, (x, w) in enumerate(in_ports):
        P("                r_%s <= s_axis_tdata[%d:%d];" % (x, i * W + w - 1, i * W))
    P("                go <= 1; st <= BUSY;")
    P("            end")
    P("            BUSY: if (done) begin")
    P("                obuf <= {%s}; uerr <= rerr;" % ", ".join("o_" + o for o in reversed(out_ports)))
    P("                st <= OUT;")
    P("            end")
    P("            OUT: if (m_axis_tready) st <= IDLE;")
    P("            default: st <= IDLE;")
    P("            endcase")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(p) + "\n"


# ---------------------------------------------------------------- AXI4-Lite
LITE_CTRL = 0x100      # bit 0: write 1 to start (clears done/range_err)
LITE_STAT = 0x104      # bit 0: done (sticky), bit 1: range_err, bit 2: busy
LITE_OUT = 0x200       # outputs base
LITE_ADDR_W = 12       # 4 KB, the smallest range Vivado's address editor likes


def lite_map(in_ports, out_ports, wl):
    """Word-addressed register map. Each port occupies ceil(w/32) 32-bit words."""
    regs, off = {}, 0
    for x, w in in_ports:
        n = (w + 31) // 32
        regs[x] = dict(offset=off * 4, words=n, width=w, dir="in")
        off += n
    assert off * 4 <= LITE_CTRL, "inputs overflow into the control register"
    nw = (wl + 31) // 32
    for i, o in enumerate(out_ports):
        regs[o] = dict(offset=LITE_OUT + i * nw * 4, words=nw, width=wl, dir="out")
    regs["CTRL"] = dict(offset=LITE_CTRL, words=1, width=32, dir="in")
    regs["STAT"] = dict(offset=LITE_STAT, words=1, width=32, dir="out")
    return regs


def lite_wrapper(name, core, wl, in_ports, out_ports):
    """AXI4-Lite register file around a generated engine.

    The AXI4-Stream wrapper is 1456 bits wide on this design, which no Zynq
    PS-PL port can carry. This trades throughput for reachability: the host
    pokes each parameter as 32-bit words, pulses start, polls done, reads the
    results back. One evaluation costs ~75 register accesses, which is
    irrelevant next to the 4572-cycle datapath.
    """
    W, AW = wl, LITE_ADDR_W
    regs = lite_map(in_ports, out_ports, wl)
    niw = sum(regs[x]["words"] for x, _ in in_ports)
    now_ = sum(regs[o]["words"] for o in out_ports)
    p = []
    P = p.append
    P("`timescale 1ns / 1ps")
    P("// Generated by hardware/gen/wrappers.py: AXI4-Lite register file for %s." % core)
    P("// %d-bit address space. Write parameters, write CTRL bit 0 to start," % AW)
    P("// poll STAT bit 0 for done, then read the outputs. Register map:")
    for x, _ in in_ports:
        r = regs[x]
        P("//   0x%03x  %-12s in   %d bit%s" % (r["offset"], x, r["width"], "" if r["width"] == 1 else "s"))
    P("//   0x%03x  CTRL         w    bit 0 = start (self-clearing)" % LITE_CTRL)
    P("//   0x%03x  STAT         r    bit 0 = done, bit 1 = range_err, bit 2 = busy" % LITE_STAT)
    for o in out_ports:
        P("//   0x%03x  %-12s out  %d bits, signed" % (regs[o]["offset"], o, W))
    P("module %s (" % name)
    P("    input  wire aclk, input wire aresetn,")
    P("    input  wire [%d:0] s_axi_awaddr, input wire [2:0] s_axi_awprot," % (AW - 1))
    P("    input  wire s_axi_awvalid, output wire s_axi_awready,")
    P("    input  wire [31:0] s_axi_wdata, input wire [3:0] s_axi_wstrb,")
    P("    input  wire s_axi_wvalid, output wire s_axi_wready,")
    P("    output wire [1:0] s_axi_bresp, output wire s_axi_bvalid, input wire s_axi_bready,")
    P("    input  wire [%d:0] s_axi_araddr, input wire [2:0] s_axi_arprot," % (AW - 1))
    P("    input  wire s_axi_arvalid, output wire s_axi_arready,")
    P("    output wire [31:0] s_axi_rdata, output wire [1:0] s_axi_rresp,")
    P("    output wire s_axi_rvalid, input wire s_axi_rready);")
    P("")
    P("    localparam CTRL_W = %d, STAT_W = %d, OUT_W0 = %d;" % (LITE_CTRL >> 2, LITE_STAT >> 2, LITE_OUT >> 2))
    P("    reg [31:0] ireg [0:%d];" % (niw - 1))
    P("    reg [31:0] oreg [0:%d];" % (now_ - 1))
    P("    reg go, done_l, err_l, busy;")
    P("    integer i;")
    P("")
    P("    // ---- AXI4-Lite write channel (registered ready: no combinational")
    P("    // path from valid to ready, which keeps the interconnect happy)")
    P("    reg awready_r, wready_r, bvalid_r, aw_en;")
    P("    reg [%d:0] awaddr_q;" % (AW - 1))
    P("    assign s_axi_awready = awready_r;")
    P("    assign s_axi_wready  = wready_r;")
    P("    assign s_axi_bvalid  = bvalid_r;")
    P("    assign s_axi_bresp   = 2'b00;   // always OKAY")
    P("    wire wr_fire = awready_r && s_axi_awvalid && wready_r && s_axi_wvalid;")
    P("    wire [%d:0] wr_word = awaddr_q[%d:2];" % (AW - 3, AW - 1))
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin awready_r <= 0; aw_en <= 1; awaddr_q <= 0; end")
    P("        else if (!awready_r && s_axi_awvalid && s_axi_wvalid && aw_en) begin")
    P("            awready_r <= 1; awaddr_q <= s_axi_awaddr; aw_en <= 0;")
    P("        end else if (s_axi_bready && bvalid_r) begin awready_r <= 0; aw_en <= 1; end")
    P("        else awready_r <= 0;")
    P("    end")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) wready_r <= 0;")
    P("        else if (!wready_r && s_axi_wvalid && s_axi_awvalid && aw_en) wready_r <= 1;")
    P("        else wready_r <= 0;")
    P("    end")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) bvalid_r <= 0;")
    P("        else if (wr_fire && !bvalid_r) bvalid_r <= 1;")
    P("        else if (s_axi_bready && bvalid_r) bvalid_r <= 0;")
    P("    end")
    P("")
    P("    // ---- AXI4-Lite read channel")
    P("    reg arready_r, rvalid_r;")
    P("    reg [%d:0] araddr_q;" % (AW - 1))
    P("    reg [31:0] rdata_r;")
    P("    assign s_axi_arready = arready_r;")
    P("    assign s_axi_rvalid  = rvalid_r;")
    P("    assign s_axi_rdata   = rdata_r;")
    P("    assign s_axi_rresp   = 2'b00;")
    P("    wire [%d:0] rd_word = araddr_q[%d:2];" % (AW - 3, AW - 1))
    P("    reg [31:0] rd_mux;")
    P("    always @(*) begin")
    P("        rd_mux = 32'h0;")
    P("        if (rd_word == STAT_W) rd_mux = {29'b0, busy, err_l, done_l};")
    P("        else if (rd_word >= OUT_W0 && rd_word < OUT_W0 + %d) rd_mux = oreg[rd_word - OUT_W0];" % now_)
    P("        else if (rd_word < %d) rd_mux = ireg[rd_word];   // readback of what was written" % niw)
    P("    end")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin arready_r <= 0; araddr_q <= 0; end")
    P("        else if (!arready_r && s_axi_arvalid) begin arready_r <= 1; araddr_q <= s_axi_araddr; end")
    P("        else arready_r <= 0;")
    P("    end")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin rvalid_r <= 0; rdata_r <= 0; end")
    P("        else if (arready_r && s_axi_arvalid && !rvalid_r) begin rvalid_r <= 1; rdata_r <= rd_mux; end")
    P("        else if (rvalid_r && s_axi_rready) rvalid_r <= 0;")
    P("    end")
    P("")
    P("    // ---- register file writes")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) for (i = 0; i < %d; i = i + 1) ireg[i] <= 32'h0;" % niw)
    P("        else if (wr_fire && wr_word < %d) ireg[wr_word] <= s_axi_wdata;" % niw)
    P("    end")
    P("")
    P("    // ---- core")
    asg = []
    for x, w in in_ports:
        o = regs[x]["offset"] // 4
        if w == 1:
            asg.append("    wire c_%s = ireg[%d][0];" % (x, o))
        elif w <= 32:
            asg.append("    wire signed [%d:0] c_%s = ireg[%d][%d:0];" % (w - 1, x, o, w - 1))
        else:
            asg.append("    wire signed [%d:0] c_%s = {ireg[%d][%d:0], ireg[%d]};" % (w - 1, x, o + 1, w - 33, o))
    p += asg
    P("    wire core_done, core_rerr;")
    P("    wire signed [%d:0] %s;" % (W - 1, ", ".join("o_" + o for o in out_ports)))
    P("    %s core (.clk(aclk), .rst(!aresetn), .start(go), %s, %s, .done(core_done), .range_err(core_rerr));"
      % (core, ", ".join(".%s(c_%s)" % (x, x) for x, _ in in_ports),
         ", ".join(".%s(o_%s)" % (o, o) for o in out_ports)))
    P("")
    P("    wire start_wr = wr_fire && (wr_word == CTRL_W) && s_axi_wdata[0];")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin go <= 0; done_l <= 0; err_l <= 0; busy <= 0; end")
    P("        else begin")
    P("            go <= 0;")
    P("            if (start_wr) begin go <= 1; done_l <= 0; err_l <= 0; busy <= 1; end")
    P("            else if (core_done) begin")
    P("                done_l <= 1; err_l <= core_rerr; busy <= 0;")
    nw = (W + 31) // 32
    for i, o in enumerate(out_ports):
        P("                oreg[%d] <= o_%s[31:0];" % (i * nw, o))
        if nw > 1:
            P("                oreg[%d] <= {%d'b0, o_%s[%d:32]};" % (i * nw + 1, 32 - (W - 32), o, W - 1))
    P("            end")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(p) + "\n", regs


