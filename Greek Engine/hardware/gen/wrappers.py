"""Wrappers around generated datapaths, each with a bit-exact testbench.

  bump   heston_bump_<cfg>: bump-and-reprice baseline built on the generated
         price-only pricer (same arithmetic, same shared-multiplier
         architecture): 1 base + 2*9 bumped pricings, central differences
         (P(p+h) - P(p-h)) * inv2h, with inv2h = 1/(2h) supplied by the host
         (like h itself), so the wrapper needs no divider.
  axi    <aad>_axi: AXI4-Stream wrapper for a generated AAD engine
         (10 WL-bit lanes in: S0..rho, is_call; 10 WL-bit lanes out).

    python wrappers.py bump --wl 56 --fl 28 --mults 8 --crot 3 --cvec 2
    python wrappers.py axi  --wl 56 --fl 28 --mults 8 --crot 3 --cvec 2
"""
import argparse
import os
import subprocess
import sys

import heston as H
from ir import rshift_round
from rtlgen import Gen, lit
from sched import Config

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "build")
SENS = [("delta", "S0"), ("strike_sens", "K"), ("theta_greek", "T"), ("rho_greek", "r"), ("vega", "v0"),
        ("kappa_sens", "kappa"), ("theta_sens", "theta"), ("xi_sens", "xi"), ("rho_corr", "rho")]


# ---------------------------------------------------------------- bump
def bump_wrapper(name, pricer, wl, fl):
    W = wl
    p = []
    P = p.append
    P("`timescale 1ns / 1ps")
    P("// Generated by hardware/gen/wrappers.py: bump-and-reprice baseline on %s." % pricer)
    P("module %s (" % name)
    P("    input wire clk, input wire rst, input wire start,")
    for n in H.PARAMS:
        P("    input wire signed [%d:0] %s, input wire signed [%d:0] h_%s, input wire signed [%d:0] inv2h_%s," % (W - 1, n, W - 1, n, W - 1, n))
    P("    input wire is_call,")
    for o in H.OUTPUTS:
        P("    output reg signed [%d:0] %s," % (W - 1, o))
    P("    output reg done, output reg range_err);")
    P("    localparam NP = 9, NPASS = 19, FL = %d;" % fl)
    P("    reg signed [%d:0] base [0:NP-1]; reg signed [%d:0] hv [0:NP-1]; reg signed [%d:0] iv [0:NP-1];" % (W - 1, W - 1, W - 1))
    P("    reg signed [%d:0] cur [0:NP-1]; reg signed [%d:0] pv [0:NPASS-1];" % (W - 1, W - 1))
    P("    reg call_r, pstart; wire pdone, perr; wire signed [%d:0] pprice;" % (W - 1))
    P("    %s pricer (.clk(clk), .rst(rst), .start(pstart), %s, .is_call(call_r), .price(pprice), .done(pdone), .range_err(perr));"
      % (pricer, ", ".join(".%s(cur[%d])" % (n, i) for i, n in enumerate(H.PARAMS))))
    P("    reg [2:0] st; reg [4:0] pass; reg [3:0] gi; integer i;")
    P("    reg signed [%d:0] prod;" % (2 * W - 1))
    P("    localparam IDLE = 0, SETUP = 1, RUN = 2, WAIT = 3, DIFF = 4, OUT = 5;")
    P("    always @(posedge clk) begin")
    P("        if (rst) begin st <= IDLE; done <= 0; pstart <= 0; end")
    P("        else begin")
    P("            done <= 0; pstart <= 0;")
    P("            case (st)")
    P("            IDLE: if (start) begin")
    for i, n in enumerate(H.PARAMS):
        P("                base[%d] <= %s; hv[%d] <= h_%s; iv[%d] <= inv2h_%s;" % (i, n, i, n, i, n))
    P("                call_r <= is_call; pass <= 0; st <= SETUP; range_err <= 0;")
    P("            end")
    P("            SETUP: begin")
    P("                for (i = 0; i < NP; i = i + 1)")
    P("                    if (pass != 0 && i == (pass - 1) / 2) cur[i] <= ((pass - 1) % 2 == 0) ? base[i] + hv[i] : base[i] - hv[i];")
    P("                    else cur[i] <= base[i];")
    P("                st <= RUN;")
    P("            end")
    P("            RUN: begin pstart <= 1; st <= WAIT; end")
    P("            WAIT: if (pdone) begin")
    P("                pv[pass] <= pprice; if (perr) range_err <= 1;")
    P("                if (pass == NPASS - 1) begin gi <= 0; st <= DIFF; end")
    P("                else begin pass <= pass + 1; st <= SETUP; end")
    P("            end")
    P("            DIFF: begin")
    P("                prod = (pv[2*gi+1] - pv[2*gi+2]) * iv[gi];")
    P("                prod = (prod + ($signed({{%d{1'b0}}, 1'b1}) <<< (FL - 1))) >>> FL;" % (2 * W - 1))
    P("                case (gi)")
    for i, (o, _) in enumerate(SENS):
        P("                %d: %s <= prod[%d:0];" % (i, o, W - 1))
    P("                endcase")
    P("                if (gi == NP - 1) st <= OUT; else gi <= gi + 1;")
    P("            end")
    P("            OUT: begin price <= pv[0]; done <= 1; st <= IDLE; end")
    P("            endcase")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(p) + "\n"


def bump_emulate(dp_price, q, hq, iq, n_terms=H.N_TERMS):
    prices = []
    for pas in range(19):
        qq = dict(q)
        if pas:
            i = (pas - 1) // 2
            name = H.PARAMS[i]
            qq[name] = q[name] + (hq[name] if (pas - 1) % 2 == 0 else -hq[name])
        out, _ = H.emulate(dp_price, qq, n_terms)
        prices.append(out["price"])
    res = {"price": prices[0]}
    for i, (o, name) in enumerate(SENS):
        res[o] = rshift_round((prices[2 * i + 1] - prices[2 * i + 2]) * iq[name], dp_price.g.fl)
    return res


# ---------------------------------------------------------------- AXI
def axi_wrapper(name, core, wl, in_ports=None, out_ports=None):
    """in_ports: [(port, width)] packed lane by lane (WL bits each, LSB lane first);
    out_ports: [port] (WL bits each). Defaults: full on-chip AAD engine."""
    W = wl
    in_ports = in_ports or [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    out_ports = out_ports or list(H.OUTPUTS)
    NI, NO = len(in_ports), len(out_ports)
    p = []
    P = p.append
    P("`timescale 1ns / 1ps")
    P("// Generated by hardware/gen/wrappers.py: AXI4-Stream wrapper for %s." % core)
    P("// in : %d lanes of %d bits: %s" % (NI, W, ", ".join(x for x, _ in in_ports)))
    P("// out: %d lanes of %d bits: %s ; m_axis_tuser = range_err" % (NO, W, ", ".join(out_ports)))
    P("module %s (" % name)
    P("    input wire aclk, input wire aresetn,")
    P("    input wire [%d:0] s_axis_tdata, input wire s_axis_tvalid, output wire s_axis_tready, input wire s_axis_tlast," % (NI * W - 1))
    P("    output wire [%d:0] m_axis_tdata, output wire m_axis_tvalid, input wire m_axis_tready, output wire m_axis_tlast," % (NO * W - 1))
    P("    output wire m_axis_tuser);   // 1 = range_err: an input outside the verified domain, results invalid")
    for x, w in in_ports:
        P("    reg %sr_%s;" % (("signed [%d:0] " % (w - 1)) if w > 1 else "", x))
    P("    reg go, uerr; wire done, rerr;")
    P("    wire signed [%d:0] %s;" % (W - 1, ", ".join("o_" + o for o in out_ports)))
    P("    %s core (.clk(aclk), .rst(!aresetn), .start(go), %s, %s, .done(done), .range_err(rerr));"
      % (core, ", ".join(".%s(r_%s)" % (x, x) for x, _ in in_ports), ", ".join(".%s(o_%s)" % (o, o) for o in out_ports)))
    P("    localparam IDLE = 0, BUSY = 1, OUT = 2;")
    P("    reg [1:0] st;")
    P("    reg [%d:0] obuf;" % (NO * W - 1))
    P("    assign s_axis_tready = (st == IDLE);")
    P("    assign m_axis_tvalid = (st == OUT);")
    P("    assign m_axis_tlast = 1'b1;")
    P("    assign m_axis_tdata = obuf;")
    P("    assign m_axis_tuser = uerr;")
    P("    always @(posedge aclk) begin")
    P("        if (!aresetn) begin st <= IDLE; go <= 0; end")
    P("        else begin")
    P("            go <= 0;")
    P("            case (st)")
    P("            IDLE: if (s_axis_tvalid) begin")
    for i, (x, w) in enumerate(in_ports):
        P("                r_%s <= s_axis_tdata[%d:%d];" % (x, i * W + w - 1, i * W))
    P("                go <= 1; st <= BUSY;")
    P("            end")
    P("            BUSY: if (done) begin")
    P("                obuf <= {%s}; uerr <= rerr;" % ", ".join("o_" + o for o in reversed(out_ports)))
    P("                st <= OUT;")
    P("            end")
    P("            OUT: if (m_axis_tready) st <= IDLE;")
    P("            default: st <= IDLE;")
    P("            endcase")
    P("        end")
    P("    end")
    P("endmodule")
    return "\n".join(p) + "\n"


# ---------------------------------------------------------------- tests
CASES = [([100, 100, 1, .05, .04, 1.5, .04, .3, -.9], True),
         ([100, 110, .25, 0, .0175, 1.5768, .0398, .5751, -.5711], False)]


def run_iverilog(files, top_tb):
    vvp = os.path.join(BUILD, top_tb + ".vvp")
    r = subprocess.run(["iverilog", "-g2005", "-o", vvp] + files, capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:3000])
        sys.exit(1)
    return subprocess.run(["vvp", "-n", vvp], capture_output=True, text=True).stdout


def build_core(a, price_only, name):
    cfg = Config(wl=a.wl, fl=a.fl, mults=a.mults, crot=a.crot, cvec=a.cvec, cordic_pipelined=a.pipe_cordic,
                 n_terms=a.terms, host_setup=getattr(a, "host_setup", False) and not price_only)
    dp = H.Datapath(a.wl, a.fl, greeks=not price_only)
    gen = Gen(dp, cfg, name)
    path = os.path.join(BUILD, name + ".v")
    os.makedirs(BUILD, exist_ok=True)
    open(path, "w").write(gen.emit())
    return dp, gen, path


def test_bump(a):
    W, fl = a.wl, a.fl
    dp, gen, core = build_core(a, True, a.name + "_pricer")
    wname = "heston_bump_" + a.name
    wpath = os.path.join(BUILD, wname + ".v")
    open(wpath, "w").write(bump_wrapper(wname, a.name + "_pricer", W, fl))
    tb = ["`timescale 1ns/1ps", "module tb;", "  reg clk = 0, rst = 1, start = 0; always #5 clk = ~clk;"]
    for n in H.PARAMS:
        tb.append("  reg signed [%d:0] %s, h_%s, inv2h_%s;" % (W - 1, n, n, n))
    tb.append("  reg is_call; integer errors = 0, cyc;")
    tb.append("  wire signed [%d:0] %s; wire done, range_err;" % (W - 1, ", ".join(H.OUTPUTS)))
    tb.append("  %s uut(.clk(clk), .rst(rst), .start(start), %s, .is_call(is_call), %s, .done(done), .range_err(range_err));"
              % (wname, ", ".join(".%s(%s), .h_%s(h_%s), .inv2h_%s(inv2h_%s)" % ((n,) * 6) for n in H.PARAMS),
                 ", ".join(".%s(%s)" % (o, o) for o in H.OUTPUTS)))
    tb.append("  initial begin #20 rst = 0;")
    for ci, (pv, call) in enumerate(CASES):
        q = H.quantize_inputs(pv, call, fl)
        hq = {n: max(1, int(round(1e-3 * max(abs(pv[i]), 1e-2) * 2 ** fl))) for i, n in enumerate(H.PARAMS)}
        iq = {n: int(round(2 ** fl / (2 * hq[n] / 2 ** fl))) for n in H.PARAMS}
        exp = bump_emulate(dp, q, hq, iq, a.terms)
        for n in H.PARAMS:
            tb.append("    %s = %s; h_%s = %s; inv2h_%s = %s;" % (n, lit(q[n], W), n, lit(hq[n], W), n, lit(iq[n], W)))
        tb.append("    is_call = %d; @(negedge clk) start = 1; @(negedge clk) start = 0; cyc = 0;" % q["is_call"])
        tb.append("    while (!done) begin @(posedge clk); cyc = cyc + 1; end #1;")
        tb.append("    if (range_err !== 1'b0) begin errors = errors + 1; $display(\"FAIL case %d range_err\"); end" % ci)
        for o in H.OUTPUTS:
            tb.append("    if (%s !== %s) begin errors = errors + 1; $display(\"FAIL case %d %s\"); end" % (o, lit(exp[o], W), ci, o))
        tb.append("    $display(\"bump case %d: %%0d cycles, price %%f delta %%f vega %%f\", cyc, price * 1.0 / %d.0, delta * 1.0 / %d.0, vega * 1.0 / %d.0);"
                  % (ci, 2 ** fl, 2 ** fl, 2 ** fl))
    tb.append("    if (errors == 0) $display(\"PASS: bump-and-reprice wrapper matches emulator bit-exactly\"); else $display(\"FAIL: %0d\", errors);")
    tb.append("    $finish; end")
    tb.append("endmodule")
    tbp = os.path.join(BUILD, "tb_" + wname + ".v")
    open(tbp, "w").write("\n".join(tb) + "\n")
    print(run_iverilog([tbp, wpath, core], "tb_" + wname)[-2000:])


def test_axi(a):
    W, fl = a.wl, a.fl
    dp, gen, core = build_core(a, False, a.name)
    wname = a.name + "_axi"
    wpath = os.path.join(BUILD, wname + ".v")
    host = a.host_setup
    in_ports = [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    if host:
        in_ports += [(pt, gen.width(dp.g.nodes[nid])) for nid, pt in sorted(gen.host_inputs.items())]
        out_ports = ["sum_" + x for x in dp.acc_names]
    else:
        out_ports = list(H.OUTPUTS)
    open(wpath, "w").write(axi_wrapper(wname, a.name, W, in_ports, out_ports))
    pv, call = CASES[0]
    q = H.quantize_inputs(pv, call, fl)
    exp, tr = H.emulate(dp, q, a.terms)
    if host:
        exp = {"sum_" + x: tr["acc"][x] for x in dp.acc_names}
    lane_vals = [q[n] for n in H.PARAMS] + [q["is_call"]]
    if host:
        lane_vals += [int(tr["setup"][nid]) for nid, _ in sorted(gen.host_inputs.items())]
    NI, NO = len(in_ports), len(out_ports)
    data = "".join("%0*x" % ((W + 3) // 4, v & ((1 << W) - 1)) for v in reversed(lane_vals))
    tb = ["`timescale 1ns/1ps", "module tb;", "  reg aclk = 0, aresetn = 0; always #5 aclk = ~aclk;",
          "  reg [%d:0] s_tdata; reg s_tvalid = 0, m_tready = 0; wire s_tready, m_tvalid, m_tlast;" % (NI * W - 1),
          "  wire [%d:0] m_tdata; wire m_tuser; integer errors = 0;" % (NO * W - 1),
          "  %s uut(.aclk(aclk), .aresetn(aresetn), .s_axis_tdata(s_tdata), .s_axis_tvalid(s_tvalid), .s_axis_tready(s_tready), .s_axis_tlast(1'b1),"
          " .m_axis_tdata(m_tdata), .m_axis_tvalid(m_tvalid), .m_axis_tready(m_tready), .m_axis_tlast(m_tlast), .m_axis_tuser(m_tuser));" % wname,
          "  initial begin",
          "    #20 aresetn = 1; @(negedge aclk);",
          "    if (!s_tready) begin errors = errors + 1; $display(\"FAIL: not ready when idle\"); end",
          "    s_tdata = %d'h%s; s_tvalid = 1;" % (NI * W, data),
          "    @(negedge aclk); s_tvalid = 0; s_tdata = {%d{1'bx}};" % (NI * W),
          "    wait (m_tvalid); repeat (5) @(negedge aclk);   // backpressure",
          "    if (!m_tvalid || !m_tlast) begin errors = errors + 1; $display(\"FAIL: tvalid/tlast dropped under backpressure\"); end"]
    for i, o in enumerate(out_ports):
        tb.append("    if ($signed(m_tdata[%d:%d]) !== %s) begin errors = errors + 1; $display(\"FAIL %s\"); end" % ((i + 1) * W - 1, i * W, lit(exp[o], W), o))
    tb += ["    if (m_tuser !== 1'b0) begin errors = errors + 1; $display(\"FAIL: tuser (range_err) set\"); end",
           "    m_tready = 1; @(negedge aclk); m_tready = 0; @(negedge aclk);",
           "    if (m_tvalid || !s_tready) begin errors = errors + 1; $display(\"FAIL: did not return to idle\"); end",
           "    if (errors == 0) $display(\"PASS: AXI4-Stream wrapper round trip bit-exact, backpressure handled\"); else $display(\"FAIL: %0d\", errors);",
           "    $finish; end", "endmodule"]
    tbp = os.path.join(BUILD, "tb_" + wname + ".v")
    open(tbp, "w").write("\n".join(tb) + "\n")
    print(run_iverilog([tbp, wpath, core], "tb_" + wname)[-2000:])
    return wpath


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
