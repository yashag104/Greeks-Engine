def run_iverilog(files, top_tb):
    vvp = os.path.join(BUILD, top_tb + ".vvp")
    r = subprocess.run(["iverilog", "-g2005", "-o", vvp] + files, capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:3000])
        sys.exit(1)
    return subprocess.run(["vvp", "-n", vvp], capture_output=True, text=True).stdout


def build_core(a, price_only, name):
    cfg = Config(wl=a.wl, fl=a.fl, mults=a.mults, crot=a.crot, cvec=a.cvec, cordic_pipelined=a.pipe_cordic,
                 n_terms=a.terms, host_setup=getattr(a, "host_setup", False) and not price_only)
    dp = H.Datapath(a.wl, a.fl, greeks=not price_only)
    gen = Gen(dp, cfg, name)
    path = os.path.join(BUILD, name + ".v")
    os.makedirs(BUILD, exist_ok=True)
    open(path, "w").write(gen.emit())
    return dp, gen, path


def test_bump(a):
    W, fl = a.wl, a.fl
    dp, gen, core = build_core(a, True, a.name + "_pricer")
    wname = "heston_bump_" + a.name
    wpath = os.path.join(BUILD, wname + ".v")
    open(wpath, "w").write(bump_wrapper(wname, a.name + "_pricer", W, fl))
    tb = ["`timescale 1ns/1ps", "module tb;", "  reg clk = 0, rst = 1, start = 0; always #5 clk = ~clk;"]
    for n in H.PARAMS:
        tb.append("  reg signed [%d:0] %s, h_%s, inv2h_%s;" % (W - 1, n, n, n))
    tb.append("  reg is_call; integer errors = 0, cyc;")
    tb.append("  wire signed [%d:0] %s; wire done, range_err;" % (W - 1, ", ".join(H.OUTPUTS)))
    tb.append("  %s uut(.clk(clk), .rst(rst), .start(start), %s, .is_call(is_call), %s, .done(done), .range_err(range_err));"
              % (wname, ", ".join(".%s(%s), .h_%s(h_%s), .inv2h_%s(inv2h_%s)" % ((n,) * 6) for n in H.PARAMS),
                 ", ".join(".%s(%s)" % (o, o) for o in H.OUTPUTS)))
    tb.append("  initial begin #20 rst = 0;")
    for ci, (pv, call) in enumerate(CASES):
        q = H.quantize_inputs(pv, call, fl)
        hq = {n: max(1, int(round(1e-3 * max(abs(pv[i]), 1e-2) * 2 ** fl))) for i, n in enumerate(H.PARAMS)}
        iq = {n: int(round(2 ** fl / (2 * hq[n] / 2 ** fl))) for n in H.PARAMS}
        exp = bump_emulate(dp, q, hq, iq, a.terms)
        for n in H.PARAMS:
            tb.append("    %s = %s; h_%s = %s; inv2h_%s = %s;" % (n, lit(q[n], W), n, lit(hq[n], W), n, lit(iq[n], W)))
        tb.append("    is_call = %d; @(negedge clk) start = 1; @(negedge clk) start = 0; cyc = 0;" % q["is_call"])
        tb.append("    while (!done) begin @(posedge clk); cyc = cyc + 1; end #1;")
        tb.append("    if (range_err !== 1'b0) begin errors = errors + 1; $display(\"FAIL case %d range_err\"); end" % ci)
        for o in H.OUTPUTS:
            tb.append("    if (%s !== %s) begin errors = errors + 1; $display(\"FAIL case %d %s\"); end" % (o, lit(exp[o], W), ci, o))
        tb.append("    $display(\"bump case %d: %%0d cycles, price %%f delta %%f vega %%f\", cyc, price * 1.0 / %d.0, delta * 1.0 / %d.0, vega * 1.0 / %d.0);"
                  % (ci, 2 ** fl, 2 ** fl, 2 ** fl))
    tb.append("    if (errors == 0) $display(\"PASS: bump-and-reprice wrapper matches emulator bit-exactly\"); else $display(\"FAIL: %0d\", errors);")
    tb.append("    $finish; end")
    tb.append("endmodule")
    tbp = os.path.join(BUILD, "tb_" + wname + ".v")
    open(tbp, "w").write("\n".join(tb) + "\n")
    print(run_iverilog([tbp, wpath, core], "tb_" + wname)[-2000:])


def test_axi(a):
    W, fl = a.wl, a.fl
    dp, gen, core = build_core(a, False, a.name)
    wname = a.name + "_axi"
    wpath = os.path.join(BUILD, wname + ".v")
    host = a.host_setup
    in_ports = [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    if host:
        in_ports += [(pt, gen.width(dp.g.nodes[nid])) for nid, pt in sorted(gen.host_inputs.items())]
        out_ports = ["sum_" + x for x in dp.acc_names]
    else:
        out_ports = list(H.OUTPUTS)
    open(wpath, "w").write(axi_wrapper(wname, a.name, W, in_ports, out_ports))
    pv, call = CASES[0]
    q = H.quantize_inputs(pv, call, fl)
    exp, tr = H.emulate(dp, q, a.terms)
    if host:
        exp = {"sum_" + x: tr["acc"][x] for x in dp.acc_names}
    lane_vals = [q[n] for n in H.PARAMS] + [q["is_call"]]
    if host:
        lane_vals += [int(tr["setup"][nid]) for nid, _ in sorted(gen.host_inputs.items())]
    NI, NO = len(in_ports), len(out_ports)
    data = "".join("%0*x" % ((W + 3) // 4, v & ((1 << W) - 1)) for v in reversed(lane_vals))
    tb = ["`timescale 1ns/1ps", "module tb;", "  reg aclk = 0, aresetn = 0; always #5 aclk = ~aclk;",
          "  reg [%d:0] s_tdata; reg s_tvalid = 0, m_tready = 0; wire s_tready, m_tvalid, m_tlast;" % (NI * W - 1),
          "  wire [%d:0] m_tdata; wire m_tuser; integer errors = 0;" % (NO * W - 1),
          "  %s uut(.aclk(aclk), .aresetn(aresetn), .s_axis_tdata(s_tdata), .s_axis_tvalid(s_tvalid), .s_axis_tready(s_tready), .s_axis_tlast(1'b1),"
          " .m_axis_tdata(m_tdata), .m_axis_tvalid(m_tvalid), .m_axis_tready(m_tready), .m_axis_tlast(m_tlast), .m_axis_tuser(m_tuser));" % wname,
          "  initial begin",
          "    #20 aresetn = 1; @(negedge aclk);",
          "    if (!s_tready) begin errors = errors + 1; $display(\"FAIL: not ready when idle\"); end",
          "    s_tdata = %d'h%s; s_tvalid = 1;" % (NI * W, data),
          "    @(negedge aclk); s_tvalid = 0; s_tdata = {%d{1'bx}};" % (NI * W),
          "    wait (m_tvalid); repeat (5) @(negedge aclk);   // backpressure",
          "    if (!m_tvalid || !m_tlast) begin errors = errors + 1; $display(\"FAIL: tvalid/tlast dropped under backpressure\"); end"]
    for i, o in enumerate(out_ports):
        tb.append("    if ($signed(m_tdata[%d:%d]) !== %s) begin errors = errors + 1; $display(\"FAIL %s\"); end" % ((i + 1) * W - 1, i * W, lit(exp[o], W), o))
    tb += ["    if (m_tuser !== 1'b0) begin errors = errors + 1; $display(\"FAIL: tuser (range_err) set\"); end",
           "    m_tready = 1; @(negedge aclk); m_tready = 0; @(negedge aclk);",
           "    if (m_tvalid || !s_tready) begin errors = errors + 1; $display(\"FAIL: did not return to idle\"); end",
           "    if (errors == 0) $display(\"PASS: AXI4-Stream wrapper round trip bit-exact, backpressure handled\"); else $display(\"FAIL: %0d\", errors);",
           "    $finish; end", "endmodule"]
    tbp = os.path.join(BUILD, "tb_" + wname + ".v")
    open(tbp, "w").write("\n".join(tb) + "\n")
    print(run_iverilog([tbp, wpath, core], "tb_" + wname)[-2000:])
    return wpath


def test_lite(a):
    W, fl, AW = a.wl, a.fl, LITE_ADDR_W
    dp, gen, core = build_core(a, False, a.name)
    wname = a.name + "_lite"
    wpath = os.path.join(BUILD, wname + ".v")
    host = a.host_setup
    in_ports = [(n, W) for n in H.PARAMS] + [("is_call", 1)]
    if host:
        in_ports += [(pt, gen.width(dp.g.nodes[nid])) for nid, pt in sorted(gen.host_inputs.items())]
        out_ports = ["sum_" + x for x in dp.acc_names]
    else:
        out_ports = list(H.OUTPUTS)
    v, regs = lite_wrapper(wname, a.name, W, in_ports, out_ports)
    open(wpath, "w").write(v)
    json.dump(regs, open(os.path.join(BUILD, wname + "_regs.json"), "w"), indent=1, sort_keys=True)

    pv, call = CASES[0]
    q = H.quantize_inputs(pv, call, fl)
    exp, tr = H.emulate(dp, q, a.terms)
    if host:
        exp = {"sum_" + x: tr["acc"][x] for x in dp.acc_names}
    vals = {n: q[n] for n in H.PARAMS}
    vals["is_call"] = q["is_call"]
    if host:
        for nid, pt in sorted(gen.host_inputs.items()):
            vals[pt] = int(tr["setup"][nid])

    nw = (W + 31) // 32
    t = []
    T = t.append
    T("`timescale 1ns/1ps")
    T("module tb;")
    T("  reg aclk = 0, aresetn = 0; always #5 aclk = ~aclk;")
    T("  reg [%d:0] awaddr = 0, araddr = 0; reg [31:0] wdata = 0; reg [3:0] wstrb = 4'hF;" % (AW - 1))
    T("  reg awvalid = 0, wvalid = 0, bready = 0, arvalid = 0, rready = 0;")
    T("  wire awready, wready, bvalid, arready, rvalid; wire [1:0] bresp, rresp; wire [31:0] rdata;")
    T("  reg [31:0] rd, w0, w1; reg signed [%d:0] got; integer errors = 0;" % (W - 1))
    T("  %s uut (.aclk(aclk), .aresetn(aresetn)," % wname)
    T("    .s_axi_awaddr(awaddr), .s_axi_awprot(3'b0), .s_axi_awvalid(awvalid), .s_axi_awready(awready),")
    T("    .s_axi_wdata(wdata), .s_axi_wstrb(wstrb), .s_axi_wvalid(wvalid), .s_axi_wready(wready),")
    T("    .s_axi_bresp(bresp), .s_axi_bvalid(bvalid), .s_axi_bready(bready),")
    T("    .s_axi_araddr(araddr), .s_axi_arprot(3'b0), .s_axi_arvalid(arvalid), .s_axi_arready(arready),")
    T("    .s_axi_rdata(rdata), .s_axi_rresp(rresp), .s_axi_rvalid(rvalid), .s_axi_rready(rready));")
    T("  task wr(input [%d:0] ad, input [31:0] dt); begin" % (AW - 1))
    T("    awaddr <= ad; wdata <= dt; awvalid <= 1; wvalid <= 1;")
    T("    @(posedge aclk); while (!(awready && wready)) @(posedge aclk);")
    T("    awvalid <= 0; wvalid <= 0; bready <= 1;")
    T("    @(posedge aclk); while (!bvalid) @(posedge aclk);")
    T("    if (bresp !== 2'b00) begin errors = errors + 1; $display(\"FAIL: bresp %b\", bresp); end")
    T("    bready <= 0;")
    T("  end endtask")
    T("  task rdw(input [%d:0] ad); begin" % (AW - 1))
    T("    araddr <= ad; arvalid <= 1; rready <= 1;")
    T("    @(posedge aclk); while (!arready) @(posedge aclk);")
    T("    arvalid <= 0;")
    T("    @(posedge aclk); while (!rvalid) @(posedge aclk);")
    T("    rd = rdata;")
    T("    if (rresp !== 2'b00) begin errors = errors + 1; $display(\"FAIL: rresp %b\", rresp); end")
    T("    rready <= 0;")
    T("  end endtask")
    T("  initial begin #5000000; $display(\"FAIL: timeout\"); $finish; end")
    T("  initial begin")
    T("    #20 aresetn = 1; @(posedge aclk);")
    # write every input word
    for x, w in in_ports:
        r = regs[x]
        raw = vals[x] & ((1 << w) - 1)
        for k in range(r["words"]):
            T("    wr(%d'h%03x, 32'h%08x);" % (AW, r["offset"] + 4 * k, (raw >> (32 * k)) & 0xFFFFFFFF))
    # readback check on one word
    first = in_ports[0][0]
    T("    rdw(%d'h%03x);" % (AW, regs[first]["offset"]))
    T("    if (rd !== 32'h%08x) begin errors = errors + 1; $display(\"FAIL: readback of %s\"); end"
      % (vals[first] & 0xFFFFFFFF, first))
    T("    if (errors == 0) $display(\"wrote %d input words, readback ok\");" % sum(regs[x]["words"] for x, _ in in_ports))
    # status before start
    T("    rdw(%d'h%03x); if (rd[0] !== 1'b0) begin errors = errors + 1; $display(\"FAIL: done set before start\"); end" % (AW, LITE_STAT))
    # start
    T("    wr(%d'h%03x, 32'h1);" % (AW, LITE_CTRL))
    T("    rdw(%d'h%03x); if (rd[2] !== 1'b1) begin errors = errors + 1; $display(\"FAIL: busy not set after start\"); end" % (AW, LITE_STAT))
    T("    rd = 0; while (rd[0] !== 1'b1) rdw(%d'h%03x);" % (AW, LITE_STAT))
    T("    if (rd[1] !== 1'b0) begin errors = errors + 1; $display(\"FAIL: range_err set in domain\"); end")
    T("    if (rd[2] !== 1'b0) begin errors = errors + 1; $display(\"FAIL: still busy after done\"); end")
    # read and compare every output
    for o in out_ports:
        r = regs[o]
        T("    rdw(%d'h%03x); w0 = rd; rdw(%d'h%03x); w1 = rd;" % (AW, r["offset"], AW, r["offset"] + 4))
        T("    got = {w1[%d:0], w0};" % (W - 33))
        T("    if (got !== %s) begin errors = errors + 1; $display(\"FAIL %s: got %%0d\", got); end" % (lit(exp[o], W), o))
    T("    if (errors == 0) $display(\"PASS: AXI4-Lite register file, %d outputs bit-exact\"); else $display(\"FAIL: %%0d\", errors);" % len(out_ports))
    T("    $finish; end")
    T("endmodule")
    tbp = os.path.join(BUILD, "tb_" + wname + ".v")
    open(tbp, "w").write("\n".join(t) + "\n")
    print(run_iverilog([tbp, wpath, core], "tb_" + wname)[-2000:])
    return wpath


