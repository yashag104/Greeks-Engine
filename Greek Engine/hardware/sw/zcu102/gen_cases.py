"""Turn the ZCU102/ZCU104 board vectors into a C header for the ARM program.

    python gen_cases.py          -> generated/zu_cases.h

Reads the three vector files the JTAG runs used (hardware/gen/build/
heston_aad_zu_lite_{vector,sweep,nifty}.tcl, from board_vectors.py), so the
processor run checks exactly the cases the JTAG runs passed: the single vector,
the 50-case sweep and the 50 real NIFTY days, 101 in all. Each case is the 19
register words to write (9 parameters as low/high words, then is_call) and the
10 expected outputs (signed 64-bit, Q32).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.normpath(os.path.join(HERE, "..", "..", "gen", "build"))
FILES = [("vector", "heston_aad_zu_lite_vector.tcl"), ("sweep", "heston_aad_zu_lite_sweep.tcl"),
         ("nifty", "heston_aad_zu_lite_nifty.tcl")]
OUTPUTS = ["price", "delta", "strike_sens", "theta_greek", "rho_greek", "vega", "kappa_sens",
           "theta_sens", "xi_sens", "rho_corr"]
WRITE = re.compile(r"\{(0x[0-9a-f]+) (0x[0-9a-f]+)\}")
EXPECT = re.compile(r"\{(\w+)\s+(0x[0-9a-f]+) (-?\d+)\}")


def cases(path):
    text = open(path).read()
    if "VEC_CASES" not in text:                      # single vector: VEC_WRITES / VEC_EXPECT
        w = text[text.index("VEC_WRITES"):text.index("VEC_EXPECT")]
        e = text[text.index("VEC_EXPECT"):]
        return [("S0=100 K=100 T=1 r=0.05 v0=0.04 kappa=1.5 theta=0.04 xi=0.3 rho=-0.9 call",
                 WRITE.findall(w), EXPECT.findall(e))]
    out = []
    for m in re.finditer(r"^  \{\{([^}]*)\}\n\s*\{(.*?)\}\n\s*\{(.*?)\}\}$", text, re.M | re.S):
        out.append((m.group(1), WRITE.findall(m.group(2)), EXPECT.findall(m.group(3))))
    return out


def main():
    rows, offsets, out_offs = [], None, None
    for kind, name in FILES:
        cs = cases(os.path.join(BUILD, name))
        for label, writes, expects in cs:
            offs = [int(o, 16) for o, _ in writes]
            if offsets is None:
                offsets = offs
            assert offs == offsets and len(offs) == 19, (name, label)
            names = [n for n, _, _ in expects]
            assert names == OUTPUTS, (name, label, names)
            oo = [int(o, 16) for _, o, _ in expects]
            if out_offs is None:
                out_offs = oo
            assert oo == out_offs
            rows.append((kind, label, [int(v, 16) for _, v in writes], [int(v) for _, _, v in expects]))
        print("%-6s %3d cases from %s" % (kind, len(cs), name))
    assert len(rows) == 101, len(rows)
    t = ["/* Generated by hardware/sw/zcu102/gen_cases.py from the board vectors -- do not edit. */",
         "#ifndef ZU_CASES_H", "#define ZU_CASES_H", "#include <stdint.h>",
         "#define ZU_NWORDS 19", "#define ZU_NOUT 10", "#define ZU_NCASES %d" % len(rows),
         "static const uint32_t zu_in_off[ZU_NWORDS] = {%s};" % ", ".join("0x%03x" % o for o in offsets),
         "static const uint32_t zu_out_off[ZU_NOUT] = {%s};" % ", ".join("0x%03x" % o for o in out_offs),
         "static const char *const zu_out_name[ZU_NOUT] = {%s};" % ", ".join('"%s"' % n for n in OUTPUTS),
         "typedef struct { const char *kind, *label; uint32_t w[ZU_NWORDS]; int64_t want[ZU_NOUT]; } zu_case;",
         "static const zu_case zu_cases[ZU_NCASES] = {"]
    for kind, label, w, want in rows:
        t.append('  {"%s", "%s", {%s},\n   {%s}},' % (kind, label, ", ".join("0x%08xu" % v for v in w),
                                                    ", ".join("%dLL" % v for v in want)))
    t += ["};", "#endif", ""]
    os.makedirs(os.path.join(HERE, "generated"), exist_ok=True)
    out = os.path.join(HERE, "generated", "zu_cases.h")
    open(out, "w", newline="\n").write("\n".join(t))
    print("wrote %s (%d cases)" % (out, len(rows)))


if __name__ == "__main__":
    main()
