"""Port-only testbench for switching-activity (SAIF) power analysis.

    python gen_power_tb.py heston_aad_z7h <clk_ns>      -> tb_power_heston_aad_z7h.v
    python gen_power_tb.py heston_aad_zu  <clk_ns>      -> tb_power_heston_aad_zu.v

Vivado's default power report assumes every signal toggles 12.5% of the time.
SAIF replaces that with the activity of real evaluations: the routed netlist
is simulated (power_saif.tcl) while this testbench runs four evaluations back
to back, two from the board sweep (seed 2026) and two real NIFTY days, at the
board's clock period, so toggle rates per second are real. It drives ports
only (a routed netlist has no RTL-named internals) and checks every output
against the emulator, so a broken netlist simulation cannot pass silently.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "..", "..", "gen")
sys.path.insert(0, GEN)

import heston as H                                   # noqa: E402
import host                                          # noqa: E402
from board_vectors import csv_cases, sweep_cases     # noqa: E402
from rtlgen import Gen                               # noqa: E402
from sched import Config                             # noqa: E402

CONFIGS = {"heston_aad_z7h": dict(wl=56, fl=28, mults=8, crot=3, cvec=2, cordic_pipelined=False, host_setup=True),
           "heston_aad_zu": dict(wl=64, fl=32, mults=32, crot=1, cvec=1, cordic_pipelined=True, host_setup=False)}
NIFTY = os.path.join(HERE, "..", "..", "..", "validation", "hedging", "results", "board_cases.csv")


def lit(v, w):
    return "-%d'sd%d" % (w, -v) if v < 0 else "%d'sd%d" % (w, v)


def main():
    core, clk_ns = sys.argv[1], float(sys.argv[2])
    c = CONFIGS[core]
    cfg = Config(**c)
    dp = H.Datapath(c["wl"], c["fl"])
    gen = Gen(dp, cfg, core)
    gen.emit()
    W, fl, hs = c["wl"], c["fl"], c["host_setup"]
    cases = sweep_cases(dp, 48, 2026)[0][2:4] + csv_cases(NIFTY)[:2]
    ports = sorted(gen.host_inputs.items(), key=lambda kv: kv[1]) if hs else []
    outs = ["sum_" + a for a in dp.acc_names] if hs else list(dp.outputs)
    names = (dp.acc_names if hs else dp.outputs)
    t = ["`timescale 1ns/1ps",
         "// Generated by hardware/vivado/power/gen_power_tb.py -- do not edit.",
         "module tb;",
         "  reg clk = 0, rst = 1, start = 0;",
         "  always #%.4f clk = ~clk;" % (clk_ns / 2),
         "  reg signed [%d:0] %s;" % (W - 1, ", ".join(H.PARAMS)),
         "  reg is_call;"]
    t += ["  reg signed [%d:0] %s;" % (W - 1, p) for _, p in ports]
    t += ["  wire signed [%d:0] %s;" % (W - 1, ", ".join(outs)), "  wire done, range_err;",
          "  integer errors = 0;"]
    conns = [".clk(clk)", ".rst(rst)", ".start(start)"] + [".%s(%s)" % (p, p) for p in H.PARAMS]
    conns += [".%s(%s)" % (p, p) for _, p in ports] + [".is_call(is_call)"]
    conns += [".%s(%s)" % (o, o) for o in outs] + [".range_err(range_err)", ".done(done)"]
    t += ["  %s uut(%s);" % (core, ", ".join(conns)), "  initial begin",
          "    // a netlist holds every flip-flop in its initial state for the first 100 ns",
          "    // (glbl.GSR): reset and start must come after that or start is lost",
          "    #200; repeat (4) @(posedge clk); rst = 0;"]
    for i, (p, call) in enumerate(cases):
        q = H.quantize_inputs(p, call, fl)
        full, tr = H.emulate(dp, q)
        want = tr["acc"] if hs else full
        t.append("    // case %d: %s" % (i + 1, ", ".join("%s=%.6g" % (n, v) for n, v in zip(H.PARAMS, p))))
        t += ["    %s = %s;" % (n, lit(q[n], W)) for n in H.PARAMS] + ["    is_call = %d;" % q["is_call"]]
        if hs:
            pv = host.setup_ports(dp, gen, p, call)
            t += ["    %s = %s;" % (pt, lit(pv[pt], W)) for _, pt in ports]
        t += ["    @(posedge clk); start = 1; @(posedge clk); start = 0;",
              "    fork : wait_done_%d" % (i + 1),
              "      begin wait (done); disable wait_done_%d; end" % (i + 1),
              "      begin repeat (%d) @(posedge clk); $display(\"FAIL: done never came (case %d)\"); $finish; end" % (
                  6000 if hs else 2500, i + 1),
              "    join",
              "    @(posedge clk);"]
        for o, n in zip(outs, names):
            t.append("    if (%s !== %s) begin errors = errors + 1; $display(\"MISMATCH case %d %s\"); end"
                     % (o, lit(want[n], W), i + 1, o))
        t.append("    if (range_err) begin errors = errors + 1; $display(\"RANGE_ERR case %d\"); end" % (i + 1))
        t.append("    $display(\"progress: evaluation %d of %d done at %%0t\", $time);" % (i + 1, len(cases)))
    t += ["    if (errors == 0) $display(\"PASS: power testbench, %d evaluations bit-exact\");" % len(cases),
          "    else $display(\"FAIL: %0d mismatches\", errors);", "    $finish;", "  end", "endmodule", ""]
    out = os.path.join(HERE, "tb_power_%s.v" % core)
    open(out, "w").write("\n".join(t))
    print("wrote", out)


if __name__ == "__main__":
    main()
